package ru.nsu.p2p.common.protocol.core;

/**
 * Базовый интерфейс для всех сетевых пакетов (Payload), передаваемых по TCP.
 * Архитектурно это маркерный интерфейс, который гарантирует, что любой объект,
 * отправляемый в сеть, знает свой {@link MessageType}.
 */
public interface Message {

    /**
     * Возвращает тип данного сообщения для формирования заголовка перед отправкой.
     */
    MessageType getType();

}