package ru.nsu.p2p.common.utils;

/**
 * Жесткие правила и константы нашего кастомного бинарного TCP-протокола.
 * Эти значения должны быть идентичны на всех клиентах и на Трекере.
 */
public final class ProtocolRules {

    /**
     * Магическое число (Magic Bytes) отправляется в самом начале каждого пакета.
     * Зачем нужно: Если к нашему открытому порту подключится случайный сканер портов
     * или HTTP-браузер, мы сразу прочитаем первые 2 байта. Если это не 0x5032,
     * мы мгновенно разрываем соединение, не тратя ресурсы на парсинг мусора.
     */
    public static final short MAGIC_BYTES = 0x5032;

    /**
     * Версия протокола. Позволяет в будущем менять структуру пакетов,
     * сохраняя обратную совместимость (или корректно отклоняя старых клиентов).
     */
    public static final byte PROTOCOL_VERSION = 1;

    /**
     * Стандартный размер одного куска файла (чанка) при разбиении.
     * 1 Мегабайт — оптимальный баланс между накладными расходами на сеть (заголовки)
     * и потреблением оперативной памяти при проверке хешей.
     */
    public static final int DEFAULT_CHUNK_SIZE_BYTES = 1024 * 1024;

    /**
     * Максимально допустимый размер полезной нагрузки (Payload) в одном TCP-пакете.
     * Зачем нужно: Защита от OutOfMemoryError (OOM). Если злоумышленник пришлет заголовок,
     * где payloadLength = 2 Гигабайта, наш клиент попытается выделить byte[2GB] и упадет.
     * Ограничиваем размер чанком + небольшим запасом на метаданные.
     */
    public static final int MAX_PAYLOAD_SIZE = DEFAULT_CHUNK_SIZE_BYTES + 1024;

    private ProtocolRules() {}
}