package ru.nsu.p2p.common.transfer;

/**
 * Жизненный цикл исходящей передачи (раздачи) файла.
 */
public enum ShareState {
    PREPARING, // Ядро читает файл, считает SHA-256 чанков и регистрирует манифест на Трекере.
    SHARING,   // Файл успешно опубликован и доступен для скачивания другим пирам.
    STOPPED,   // Раздача остановлена пользователем (клиент больше не отвечает на запросы по этому файлу).
    FAILED     // Ошибка (например, исходный файл был удален или перемещен на диске).
}