package ru.nsu.p2p.common.stream;


/**
 * Абстракция потокового чтения файла из P2P-сети.
 * Реализуется в client-core. Вызывается рабочими потоками локального HTTP-сервера (в client-ui).
 *
 * Архитектурно это фасад, скрывающий сложную логику: если запрошенные байты уже скачаны
 * и проверены по хешу, они отдаются сразу. Если нет — вызов блокируется до тех пор,
 * пока нужный чанк не будет скачан у пиров, либо пока не истечет тайм-аут.
 */
public interface ReadableMedia {

    /**
     * Возвращает метаданные потока.
     */
    MediaDescriptor describe();

    /**
     * Читает последовательность байтов из P2P-сети (или локального кэша).
     * Внимание: метод блокирующий! Он должен вызываться в отдельном потоке (например, потоке HTTP-обработчика),
     * чтобы не заморозить UI.
     *
     * @param offset    Смещение в байтах от начала файла, с которого нужно начать чтение.
     * @param maxBytes  Максимальное количество байт, которое готов принять вызывающий код.
     * @param timeoutMs Максимальное время ожидания (в миллисекундах), если данные еще не скачаны.
     * @return Массив байтов. Длина массива может быть меньше maxBytes, если достигнут конец файла
     *         или скачана только часть запрошенного блока.
     * @throws ru.nsu.p2p.common.error.ClientOperationException с кодом DATA_NOT_READY, если истек таймаут,
     *         а нужный чанк так и не был скачан.
     */
    byte[] readAt(long offset, int maxBytes, int timeoutMs);

    /**
     * Закрывает поток чтения и освобождает ресурсы (например, отменяет приоритетную загрузку чанков).
     */
    void close();
}
