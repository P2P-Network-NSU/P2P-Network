package ru.nsu.p2p.common.transfer;

/**
 * Жизненный цикл входящей передачи (скачивания) файла.
 * Определяет строгую стейт-машину для UI.
 */
public enum TransferState {
    QUEUED,            // В очереди на скачивание (например, если есть лимит на одновременные загрузки).
    DOWNLOADING,       // Активно скачивается (идет обмен чанками с пирами).
    SWITCHING_PEER,    // Текущий пир отвалился или прислал битый чанк, ядро ищет нового пира. (Отказоустойчивость!)
    WAITING_FOR_PEERS, // Нет доступных пиров с нужными чанками. Загрузка простаивает.
    PAUSED,            // Поставлено на паузу пользователем.
    VERIFYING,         // Финальная проверка целостности файла на диске после скачивания всех чанков.
    COMPLETED,         // Успешно скачано и проверено.
    FAILED,            // Критическая ошибка (например, нет места на диске). См. lastError в снимке.
    CANCELLED          // Отменено пользователем, временные файлы удалены.
}