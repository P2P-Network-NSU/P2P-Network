package ru.nsu.p2p.common.client;

/**
 * Состояние подключения клиента к центральному Трекеру.
 * Используется для отображения глобального статуса сети в UI (например, цветной индикатор в статус-баре).
 */
public enum ConnectionState {
    CONNECTING, // Клиент пытается установить TCP-соединение с Трекером.
    ONLINE,     // Соединение установлено, Heartbeat-сообщения успешно отправляются.
    OFFLINE,    // Связь с Трекером потеряна (например, нет интернета). Клиент будет пытаться переподключиться.
    STOPPED     // Клиент штатно остановлен пользователем (ClientLifecycle.shutdown).
}